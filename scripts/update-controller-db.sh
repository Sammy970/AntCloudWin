#!/bin/zsh
# Regenerates Core/Controllers/KnownControllers.cs: the controllers Moonlight on Windows recognises, from the
# same two lists it uses — SDL's built-in mappings and the community SDL_GameControllerDB — keeping only their
# Windows (XInput, Windows.Gaming.Input and DirectInput) entries. Run it now and then to pick up new controllers.
set -euo pipefail
cd "$(dirname "$0")/.."

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
curl -fsSL -o "$TMP/community.txt" https://raw.githubusercontent.com/mdqinc/SDL_GameControllerDB/master/gamecontrollerdb.txt
curl -fsSL -o "$TMP/sdl2.h" https://raw.githubusercontent.com/libsdl-org/SDL/SDL2/src/joystick/SDL_gamecontrollerdb.h
curl -fsSL -o "$TMP/sdl3.h" https://raw.githubusercontent.com/libsdl-org/SDL/main/src/joystick/SDL_gamepad_db.h

mkdir -p Core/Controllers
python3 -I - "$TMP" Core/Controllers/KnownControllers.cs <<'EOF'
import re, sys, os
from collections import Counter
tmp, out = sys.argv[1], sys.argv[2]

def ids(guid):
    """Vendor and product from an SDL GUID: new-style GUIDs start with the bus (USB/Bluetooth)."""
    g = guid.lower()
    le = lambda s: int(s[2:4] + s[0:2], 16)
    if g[0:4] in ("0300", "0500"):
        return le(g[8:12]), le(g[16:20])
    return le(g[0:4]), le(g[16:20])

known = {}
def add(line):
    parts = line.split(",")
    if len(parts) < 2 or not re.fullmatch(r"[0-9a-fA-F]{32}", parts[0]):
        return
    v, p = ids(parts[0])
    if v and p:
        # Several entries can share an ID (clones reuse popular IDs); the most common name wins.
        known.setdefault((v, p), Counter())[parts[1].strip()] += 1

for line in open(os.path.join(tmp, "community.txt")):
    if "platform:Windows" in line:
        add(line.strip())

windows = ("#ifdef SDL_JOYSTICK_XINPUT", "#ifdef SDL_JOYSTICK_WGI", "#ifdef SDL_JOYSTICK_DINPUT")
for name in ("sdl2.h", "sdl3.h"):
    inside = False
    for line in open(os.path.join(tmp, name)):
        if line.startswith(windows):
            inside = True
        elif inside and line.startswith("#endif"):
            inside = False
        elif inside:
            m = re.search(r'"([^"]+)"', line)
            if m:
                add(m.group(1))

with open(out, "w") as f:
    f.write("// Generated by scripts/update-controller-db.sh — do not edit.\n")
    f.write("// Controllers SDL (and so Moonlight) has a Windows mapping for, from SDL's built-in list and the\n")
    f.write("// community SDL_GameControllerDB, keyed by USB vendor and product ID.\n\n")
    f.write("namespace AntCloud.Core.Controllers;\n\n")
    f.write("static class KnownControllers\n{\n")
    f.write("    public static readonly Dictionary<uint, string> Names = new()\n    {\n")
    for (v, p), names in sorted(known.items()):
        n = names.most_common(1)[0][0]
        f.write('        [0x%04x_%04x] = "%s",\n' % (v, p, n.replace("\\", "\\\\").replace('"', '\\"')))
    f.write("    };\n}\n")
print(f"{len(known)} controllers")
EOF
